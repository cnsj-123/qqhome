"""Strict committed official Room schema gate. A bootstrap export never makes this gate green."""
import argparse, hashlib, json, pathlib, re, subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
BASE = "245e1475cd1d47a4205ab49f75d5e06d22de701c"
SCHEMA = "app/schemas/com.qq.closie.life.data.database.LifeDatabase"

def git_bytes(root, *args):
    return subprocess.check_output(["git", *args], cwd=root, stderr=subprocess.PIPE)

def committed_file(root, relative):
    """Require both index tracking and HEAD content; staged-only/untracked files do not qualify."""
    git_bytes(root, "ls-files", "--error-unmatch", "--", relative)
    committed = git_bytes(root, "show", f"HEAD:{relative}")
    actual = (root / relative).read_bytes()
    if actual != committed:
        raise ValueError(f"Generated bytes differ from committed HEAD: {relative}")
    git_bytes(root, "diff", "HEAD", "--exit-code", "--", relative)
    return committed

def verify(root, history_only=False):
    errors, hashes = [], {}
    def check(label, action):
        try:
            action()
        except (OSError, ValueError, KeyError, TypeError, AssertionError, subprocess.CalledProcessError) as error:
            errors.append(f"{label}: {error}")

    check("Pinned R2 commit history", lambda: git_bytes(root, "cat-file", "-e", f"{BASE}^{{commit}}"))
    for version in range(1, 5):
        relative = f"{SCHEMA}/{version}.json"
        def historical(relative=relative):
            original = git_bytes(root, "show", f"{BASE}:{relative}")
            head = git_bytes(root, "show", f"HEAD:{relative}")
            assert head == original, "published schema was changed in Git history"
            actual = (root / relative).read_bytes()
            assert actual.replace(b"\r\n", b"\n") == original.replace(b"\r\n", b"\n"), "published schema changed on disk"
            git_bytes(root, "ls-files", "--error-unmatch", "--", relative)
            git_bytes(root, "diff", "HEAD", "--exit-code", "--", relative)
            hashes[str(version)] = hashlib.sha256(original).hexdigest()
        check(f"Historical Room {version}", historical)

    def versions():
        db = (root / "app/src/main/java/com/qq/closie/life/data/database/LifeDatabase.kt").read_text(encoding="utf-8-sig")
        assert re.search(r"version\s*=\s*5\s*,", db), "Room database must be v5"
        migration = (root / "app/src/main/java/com/qq/closie/life/data/database/FinanceV16Migration.kt").read_text(encoding="utf-8-sig")
        assert "Migration(4, 5)" in migration
        chain = (root / "app/src/main/java/com/qq/closie/life/data/database/LifeMigrations.kt").read_text(encoding="utf-8-sig")
        assert "arrayOf(MIGRATION_1_2, MIGRATION_2_3, MIGRATION_3_4, FinanceV16Migration)" in chain
        backup = (root / "app/src/main/java/com/qq/closie/data/backup/BackupManager.kt").read_text(encoding="utf-8-sig")
        assert re.search(r"BACKUP_FORMAT_VERSION\s*=\s*5\b", backup)
        assert re.search(r"BACKUP_SCHEMA_VERSION\s*=\s*1\b", backup)
        importer = (root / "app/src/main/java/com/qq/closie/data/backup/BackupImporter.kt").read_text(encoding="utf-8-sig")
        assert 'manifest.formatVersion >= 5' in importer and 'finance.has("v16")' in importer
        cipher = (root / "app/src/main/java/com/qq/closie/data/backup/EncryptedBackupEnvelope.kt").read_text(encoding="utf-8-sig")
        assert re.search(r"const val VERSION\s*=\s*2\b", cipher)
    check("Database/migration/backup version contract", versions)

    if not history_only:
        def official():
            raw = committed_file(root, f"{SCHEMA}/5.json")
            schema = json.loads(raw)
            assert schema["formatVersion"] == 1 and schema["database"]["version"] == 5
            assert re.fullmatch(r"[0-9a-f]{32}", schema["database"]["identityHash"])
            historical = json.loads(git_bytes(root, "show", f"{BASE}:{SCHEMA}/4.json"))
            design = json.loads((root / "engineering/v16/schema-v5.json").read_text(encoding="utf-8-sig"))
            expected = {entity["tableName"] for entity in historical["database"]["entities"]} | {table["name"] for table in design["tables"]}
            actual = [entity["tableName"] for entity in schema["database"]["entities"]]
            assert len(actual) == len(set(actual)) and set(actual) == expected, "official entity set differs from migration contract"
            entities = {entity["tableName"]: entity for entity in schema["database"]["entities"]}
            for table, prefix in (("finance_entry_timing", "posted"), ("finance_observations", "observed")):
                fields={field["columnName"]:field for field in entities[table]["fields"]}
                for suffix in ("LocalDate", "ZoneId", "DayStartAt", "DayEndExclusive", "DateBasisVersion"):
                    assert not fields[prefix+suffix]["notNull"], "civil-date evidence must remain nullable for legacy archives"
            hashes["5"] = hashlib.sha256(raw).hexdigest()
            git_bytes(root, "diff", "HEAD", "--exit-code", "--", SCHEMA)
        check("Committed KSP official Room 5 (bootstrap must fail until committed)", official)
    return {"check": "published-history" if history_only else "strict-committed-official-room-schema",
            "status": "FAIL" if errors else "PASS", "comparisonBase": BASE, "errors": errors, "schemaSha256": hashes,
            "versions": {"roomDatabase": 5, "backupFormat": 5, "backupManifestSchema": 1, "aeadEnvelope": 2},
            "androidRuntime": "UNVERIFIED"}

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--history-only", action="store_true")
    parser.add_argument("--report", type=pathlib.Path, default=pathlib.Path("engineering/v16/ci-logs/room-schema-check.json"))
    args = parser.parse_args()
    result = verify(ROOT, args.history_only)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False))
    raise SystemExit(result["status"] != "PASS")
